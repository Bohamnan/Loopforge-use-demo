"""Temporary original files of unconfirmed drafts: {DATA_DIR}/drafts/<draft_id><ext>.

File names are generated by the server (id + extension derived from the verified content
type); user file names are never used. Every path is checked to stay inside the directory.
"""

import os
import re
from dataclasses import dataclass
from pathlib import Path

EXTENSIONS = {"application/pdf": ".pdf", "image/jpeg": ".jpg", "image/png": ".png"}
_ID_RE = re.compile(r"[A-Za-z0-9-]{1,64}")
_NAME_RE = re.compile(r"[A-Za-z0-9-]{1,64}\.(?:pdf|jpg|png)")


@dataclass(frozen=True)
class StoredFile:
    """A file found in the drafts directory."""

    name: str
    modified_at: float  # POSIX seconds


class DraftFileStore:
    """Reads, writes and deletes draft files; creates the directory on construction."""

    def __init__(self, data_dir: Path) -> None:
        self._root = (data_dir / "drafts").resolve()
        self._root.mkdir(parents=True, exist_ok=True)

    def save(self, draft_id: str, content_type: str, content: bytes) -> str:
        """Write a new file (never overwrites) and return its server-generated name."""
        if content_type not in EXTENSIONS:
            raise ValueError("unsupported content type")
        if not _ID_RE.fullmatch(draft_id):
            raise ValueError("invalid draft id")
        name = f"{draft_id}{EXTENSIONS[content_type]}"
        with open(self._root / name, "xb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        return name

    def resolve(self, name: str) -> Path:
        """Return the absolute path of a stored file; reject anything outside the directory."""
        if not _NAME_RE.fullmatch(name):
            raise ValueError("invalid file name")
        path = (self._root / name).resolve()
        if path.parent != self._root:
            raise ValueError("invalid file name")
        return path

    def read(self, name: str) -> bytes:
        return self.resolve(name).read_bytes()

    def delete(self, name: str) -> bool:
        """Delete a file; return False if it did not exist (idempotent)."""
        path = self.resolve(name)
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        return True

    def list_files(self) -> list[StoredFile]:
        """Regular files in the directory with their modification times."""
        return [
            StoredFile(entry.name, entry.stat().st_mtime)
            for entry in self._root.iterdir()
            if entry.is_file() and not entry.is_symlink()
        ]
