# ---- reading the frozen document ---------------------------------------------------------------


def resolve(node: dict) -> dict:
    """Follow local ``$ref`` pointers until a concrete object is reached."""
    spec = load_spec()
    while "$ref" in node:
        target = spec
        for part in node["$ref"].removeprefix("#/").split("/"):
            target = target[part]
        node = target
    return node


def frozen_operations() -> dict[tuple[str, str], dict]:
    return {
        (path, method): op
        for path, item in load_spec()["paths"].items()
        for method, op in item.items()
        if method in HTTP_METHODS
    }


def frozen_triples() -> set[tuple[str, str, int]]:
    return {
        (path, method, int(status))
        for (path, method), op in frozen_operations().items()
        for status in op["responses"]
    }


def frozen_response(path: str, method: str, status: int) -> dict:
    return resolve(frozen_operations()[(path, method)]["responses"][str(status)])


def documented_codes(path: str, method: str, status: int) -> set[str]:
    """Error codes a documented response names: its examples plus codes in its description."""
    response = frozen_response(path, method, status)
    examples = response.get("content", {}).get("application/json", {}).get("examples", {})
    codes = {resolve(e)["value"]["code"] for e in examples.values()}
    enum = load_spec()["components"]["schemas"]["ErrorCode"]["enum"]
    return codes | {c for c in enum if re.search(rf"\b{c}\b", response["description"])}


def cookie_documented(path: str, method: str, status: int) -> bool:
    return "Set-Cookie" in frozen_response(path, method, status).get("headers", {})


def documented_max_age() -> str:
    description = load_spec()["components"]["headers"]["BrowserCookie"]["description"]
    (max_age,) = re.findall(r"Max-Age=(\d+)", description)
    return max_age


# ---- test environment --------------------------------------------------------------------------


@dataclass
class Api:
    app: FastAPI
    client: TestClient
    settings: Settings
    parser: FakeParserClient
    chat: FakeChatClient

    def upload(
        self, content: bytes | None = None, name: str = "cv.pdf", mime: str = "application/pdf"
    ) -> HttpResponse:
        data = PDF if content is None else content
        return self.client.post(SESSIONS, files={"file": (name, data, mime)})

    def browser(self, browser_id: str | None) -> TestClient:
        """Another client of the same application: another browser, or none at all."""
        other = TestClient(self.app, raise_server_exceptions=False)
        if browser_id is not None:
            other.cookies.set("browser_id", browser_id)
        return other


def build_api(root: Path) -> Api:
    data, files = root / "data", root / "file"
    data.mkdir(parents=True)
    files.mkdir()
    settings = Settings(_env_file=None, data_dir=data, file_dir=files)
    init_drafts_db(data / "drafts.db")
    init_resumes_db(data / "resumes.db")
    parser = FakeParserClient(result=make_raw_result())
    chat = FakeChatClient(result=make_chat_result("ok", [("current_city", "BEIJING")]))
    app = create_app(settings, parser_client=parser, chat_client=chat, clock=FakeClock())
    return Api(app, TestClient(app, raise_server_exceptions=False), settings, parser, chat)


def boom(*_args: object, **_kwargs: object) -> None:
    raise RuntimeError("ZZ-secret-boom")


def new_session(api: Api) -> str:
    return api.upload().json()["session_id"]


def saved_session(api: Api) -> tuple[str, str]:
    """A reviewing session confirmed and saved. Returns (session id, resume id)."""
    sid = new_session(api)
    confirm = api.client.post(RESUME.format(session_id=sid), json={"confirmed": True})
    return sid, confirm.json()["resume_id"]


def pending_session(api: Api) -> str:
    """A new session of an already saved person: confirming it keeps an update candidate."""
    saved_session(api)
    sid = new_session(api)
    confirm = api.client.post(RESUME.format(session_id=sid), json={"confirmed": True})
    assert confirm.status_code == 200, confirm.text
    return sid


def with_card(api: Api) -> tuple[str, str]:
    """A session with one assistant message carrying a suggestion card. Returns (sid, mid)."""
    sid = new_session(api)
    reply = api.client.post(MESSAGES.format(session_id=sid), json={"content": "hi"})
    return sid, reply.json()["assistant_message"]["message_id"]


def remove_archive_files(api: Api) -> None:
    for path in api.settings.file_dir.iterdir():
        path.unlink()


