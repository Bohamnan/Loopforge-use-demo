def cookie_attrs(header: str) -> dict[str, str]:
    """Split one Set-Cookie header into its value (under ``__value__``) and attributes."""
    name_value, *rest = [part.strip() for part in header.split(";")]
    attrs = {key: value for key, _, value in (part.partition("=") for part in rest)}
    attrs["__value__"] = name_value.partition("=")[2]
    assert name_value.startswith("browser_id="), header
    return attrs


def assert_cookie(scenario: Scenario, response: HttpResponse) -> None:
    issued = response.headers.get_list("set-cookie")
    if scenario.cookie == "absent":
        assert issued == [], "Set-Cookie sent where the contract does not allow it"
        return
    path, method = scenario.op
    assert cookie_documented(path, method, scenario.status), "contract documents no Set-Cookie"
    assert len(issued) == 1, issued
    attrs = cookie_attrs(issued[0])
    assert re.fullmatch(r"[A-Za-z0-9_-]{43}", attrs.pop("__value__"))
    # HttpOnly, Path and SameSite as documented; no Secure (COOKIE_SECURE defaults to false).
    assert attrs == {
        "HttpOnly": "",
        "SameSite": "Lax",
        "Path": "/",
        "Max-Age": documented_max_age(),
    }


def assert_download(response: HttpResponse) -> None:
    media = response.headers["content-type"].split(";")[0]
    assert media in load_spec()["paths"][RESUME_FILE]["get"]["responses"]["200"]["content"]
    assert response.headers["x-content-type-options"] == "nosniff"
    disposition = response.headers["content-disposition"]
    assert disposition.startswith("attachment; filename*=UTF-8''")
    assert response.content == PDF


def assert_body(scenario: Scenario, response: HttpResponse) -> None:
    path, method = scenario.op
    if scenario.status == 204:
        assert response.content == b""
    elif scenario.op == DOWNLOAD and scenario.status == 200:
        assert_download(response)
    else:
        schema = frozen_response(path, method, scenario.status)["content"]["application/json"]
        assert validate_against(schema["schema"], response.json()) == []
    if scenario.code is not None:
        assert response.json()["code"] == scenario.code
        assert scenario.code in documented_codes(path, method, scenario.status)
        assert "ZZ-secret" not in response.text  # B-03: no internal detail leaks


