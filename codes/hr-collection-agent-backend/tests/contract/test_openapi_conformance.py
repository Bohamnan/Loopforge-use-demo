LIMIT_KEYS = ("maxLength", "maxItems", "minLength", "pattern")


def _limits(prop: dict) -> dict:
    """maxLength / maxItems / minLength / pattern of a property, in OpenAPI or Pydantic form."""
    found: dict = {}
    for candidate in (prop, *prop.get("anyOf", [])):
        for key in LIMIT_KEYS:
            if key in candidate:
                found[key] = candidate[key]
        if "maxLength" in candidate.get("items", {}):
            found["item_maxLength"] = candidate["items"]["maxLength"]
    return found


