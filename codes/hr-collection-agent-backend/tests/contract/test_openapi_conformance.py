"""Contract conformance against the frozen OpenAPI 0.2.0 (task 3.1). The contract is never edited.

What is checked, all derived from the frozen document itself:

* the 13 paths, methods and ``operationId`` values of ``app.openapi()`` equal the frozen ones,
  and so do the success statuses;
* every (path, method, status) triple of the frozen document is produced by one real request,
  and its body validates against the schema the document names for that status;
* error codes are the documented ones and the enum equals the code's ``ErrorCode``;
* ``Set-Cookie``: a response the document does not describe as setting the cookie never sends
  one; one that does sends it with the documented attributes;
* the limits of ``ResumeFieldsUpdate`` and the entry models equal the frozen ones, and the server
  enforces one representative value per kind of limit.

Known difference: ``app.openapi()`` is generated by FastAPI and lists only the success statuses
plus its default 422. Error statuses come from the unified error handlers and are compared
through real responses instead.
"""

