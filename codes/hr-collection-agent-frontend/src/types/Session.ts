// Mirror of OpenAPI 0.2.0 session schemas (see ResumeModel.ts for the maintenance rule).
import type { ArchivedResume } from './Archive';
import type { ChatMessage } from './Conversation';
import type { ResumeFields, ResumeFieldsUpdate, ResumeValues } from './ResumeModel';

export type OriginalFileContentType = 'application/pdf' | 'image/jpeg' | 'image/png';

export interface OriginalFileInfo {
  /** Original file name, display only. */
  filename: string;
  content_type: OriginalFileContentType;
  /** 1 .. 10485760 */
  size_bytes: number;
}

/** reviewing = being checked (editable, chat, save); saved = read-only except the confirmed update. */
export const SESSION_STATUSES = ['reviewing', 'saved'] as const;
export type SessionStatus = (typeof SESSION_STATUSES)[number];

/** none = no candidate; pending = saved before, new content waits for the user's update confirmation; applied = candidate applied. */
export const UPDATE_STATES = ['none', 'pending', 'applied'] as const;
export type UpdateState = (typeof UPDATE_STATES)[number];

export interface SessionSummary {
  session_id: string;
  /** Generated by the backend: "简历 · name" or "未命名简历". */
  name: string;
  status: SessionStatus;
  /** ISO 8601 UTC; the list is ordered by it, newest first. */
  last_active_at: string;
}

export interface SessionListResponse {
  items: SessionSummary[];
}

/** Frozen "this time" content when the save hit the idempotency key; compared with `resume` to get the diff. */
export interface UpdateCandidate {
  fields: ResumeValues;
  original_file: OriginalFileInfo;
}

/** fields is set for reviewing sessions; resume for saved sessions; update_candidate only when update_state is pending. */
export interface SessionDetail {
  session_id: string;
  name: string;
  status: SessionStatus;
  update_state: UpdateState;
  original_file: OriginalFileInfo;
  fields: ResumeFields | null;
  resume: ArchivedResume | null;
  update_candidate: UpdateCandidate | null;
  /** All chat messages in time order. */
  messages: ChatMessage[];
  created_at: string;
  updated_at: string;
  last_active_at: string;
}

export interface SessionFieldsUpdateRequest {
  fields: ResumeFieldsUpdate;
}

export interface SessionFieldsResponse {
  session_id: string;
  fields: ResumeFields;
  updated_at: string;
}
